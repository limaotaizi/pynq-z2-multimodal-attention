# -*- coding: utf-8 -*-
"""attn_vectors4.npz  ->  golden_m4.h（裸机程序内嵌的金标准）

    python -I -X utf8 gen_golden.py

数据来源是 deploy/attn_vectors4.npz —— 与板端 Python 路径**同一份**向量，
也就是 xsim testbench 逐位验过的那一份。裸机程序只要和它一致，
就与 `board_dump4.py` + `cmp_dump4.py` 的结果同口径。

数组顺序与 deploy/m4_map.py 的 ARRAYS 完全一致（28 个 / 5,504 字）。
一致性在生成时校验：这里再算一遍总数，和 m4_map.TOTAL_WORDS 对不上就报错。
"""
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
DEPLOY = os.path.join(os.path.dirname(HERE), "deploy")
sys.path.insert(0, DEPLOY)

import m4_map                                                    # noqa: E402

NPZ = os.path.join(DEPLOY, "attn_vectors4.npz")
OUT = os.path.join(HERE, "src", "golden_m4.h")

PER_LINE = 12


def emit_array(fh, ctype, name, vals, signed=True):
    n = len(vals)
    fh.write("static const %s %s[%d] = {\n" % (ctype, name, n))
    line = []
    for i, v in enumerate(vals):
        line.append("0x%04X" % (int(v) & 0xFFFF))
        if len(line) == PER_LINE:
            fh.write("    " + ", ".join(line) + ",\n")
            line = []
    if line:
        fh.write("    " + ", ".join(line) + ",\n")
    fh.write("};\n\n")


def main():
    z = np.load(NPZ, allow_pickle=False)
    in_q = z["in_q"].astype(np.int64).reshape(-1)
    if in_q.size != m4_map.N_IN:
        raise SystemExit("in_q has %d words, m4_map says %d"
                         % (in_q.size, m4_map.N_IN))

    total = 0
    for name, base, n in m4_map.ARRAYS:
        a = z[name].astype(np.int64).reshape(-1)
        if a.size != n:
            raise SystemExit("%s has %d words, map says %d" % (name, a.size, n))
        total += n
    if total != m4_map.TOTAL_WORDS:
        raise SystemExit("array total %d != m4_map.TOTAL_WORDS %d"
                         % (total, m4_map.TOTAL_WORDS))

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("/* golden_m4.h -- GENERATED by gen_golden.py, do not edit.\n")
        fh.write(" *\n")
        fh.write(" * source : attn_vectors4.npz\n")
        fh.write(" * map    : deploy/m4_map.py ARRAYS (%d arrays, %d words)\n"
                 % (len(m4_map.ARRAYS), m4_map.TOTAL_WORDS))
        fh.write(" * engine : %d clk = %.2f ms @100 MHz\n"
                 % (m4_map.ENGINE_CYCLES, m4_map.ENGINE_MS_AT_100MHZ))
        fh.write(" *\n")
        fh.write(" * Everything is int16 two's complement, printed as 0x%%04X so what\n")
        fh.write(" * is in the file is exactly the bit pattern the engine puts in scratch.\n")
        fh.write(" */\n")
        fh.write("#ifndef GOLDEN_M4_H\n#define GOLDEN_M4_H\n\n")
        fh.write("#include <stdint.h>\n\n")
        fh.write("#define G_N_IN          %d\n" % m4_map.N_IN)
        fh.write("#define G_TOTAL_WORDS   %d\n" % m4_map.TOTAL_WORDS)
        fh.write("#define G_ENGINE_CYCLES %dLL\n" % m4_map.ENGINE_CYCLES)
        fh.write("\n")
        fh.write("typedef struct {\n")
        fh.write("    const char     *name;\n")
        fh.write("    uint16_t        base;   /* scratch word index */\n")
        fh.write("    uint16_t        n;\n")
        fh.write("    const int16_t  *exp;\n")
        fh.write("} g_array_t;\n\n")

        emit_array(fh, "int16_t", "G_IN_Q", in_q)
        for name, base, n in m4_map.ARRAYS:
            emit_array(fh, "int16_t", "G_%s" % name.upper(),
                       z[name].astype(np.int64).reshape(-1))

        fh.write("static const g_array_t G_ARRAYS[%d] = {\n" % len(m4_map.ARRAYS))
        for name, base, n in m4_map.ARRAYS:
            fh.write('    { "%-4s", %4d, %4d, G_%s },\n'
                     % (name, base, n, name.upper()))
        fh.write("};\n\n")
        fh.write("#define G_N_ARRAYS  %d\n\n" % len(m4_map.ARRAYS))
        fh.write("#endif /* GOLDEN_M4_H */\n")

    nz = sum(1 for v in in_q if v != 0)
    print("golden_m4.h written: %s (%d B)" % (OUT, os.path.getsize(OUT)))
    print("  in_q        : %d words, %d non-zero" % (in_q.size, nz))
    print("  arrays      : %d, %d words total" % (len(m4_map.ARRAYS), total))
    print("  engine      : %d clk = %.2f ms @100 MHz"
          % (m4_map.ENGINE_CYCLES, m4_map.ENGINE_MS_AT_100MHZ))


if __name__ == "__main__":
    main()
