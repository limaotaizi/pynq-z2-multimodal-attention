# -*- coding: utf-8 -*-
"""M=4 的模块③+④（PS 侧 Python）  ->  C 头文件，供裸机程序在板上算完三类概率。

    python -I -X utf8 gen_head.py

产物（都在 src/）：
    head_m4_w.h     权重（float）：agg.Wa/ba、agg.wa/bwa（每模态）、head.0、head.3
    head_m4_gold.h  act scale + 本窗期望 logits / 概率 / 类 + 每模态的 z

真源与 PL 侧完全一致，不是重新训练或重新量化：
    权重   `_board/w_attn4_p_emotion_v_f0.npz`
           —— 与 `work2/export.py m4` 用的是同一个文件（导出脚本里写死的那条路径）
    act    `_pl/work2/out_m4_snapshot/exp_note.txt`
           —— 现役 `attn4_e4.bit` 那次导出的全局激活 scale
    输入   `_pl/deploy/attn_vectors4.npz` 的 zp{e,o,a,s}
           —— 板端逐位验收过的那 1,024 个字（4×16×16）

参考值由 `_board/ps_head.py`（板上 Python 路径同一份代码）算出：
    logits = PSHead.forward(dequant(Zp_int, act))
所以板端 C 实现只要和它一致，就等于和已验证的 Python 路径一致。

★ 为什么 Zp 要用 INT16 原值而不是 fp32：PL 交出来的就是 INT16，
  板端不可能拿到 fp32 的那一版。B 级（吃 fp32）与 C 级（吃 INT16）的差别
  就是 PL→PS 的量化损失，这里取 C 级，和板上真实链路同口径。
"""
import os
import re
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
PL = os.path.dirname(HERE)
ROOT = os.path.dirname(PL)
BOARD = os.path.join(ROOT, "_board")
sys.path.insert(0, BOARD)

from ps_head import PSHead                                        # noqa: E402

W_NPZ = os.path.join(BOARD, "w_attn4_p_emotion_v_f0.npz")
NOTE = os.path.join(PL, "work2", "out_m4_snapshot", "exp_note.txt")
VEC = os.path.join(PL, "deploy", "attn_vectors4.npz")

SRC = os.path.join(HERE, "src")
OUT_W = os.path.join(SRC, "head_m4_w.h")
OUT_G = os.path.join(SRC, "head_m4_gold.h")

MODS = ["e", "o", "a", "s"]
PER_LINE_W = 6
PER_LINE_I = 10


def read_act():
    txt = open(NOTE, encoding="utf-8").read()
    m = re.search(r"mode=(\S+)", txt)
    if not m or m.group(1) != "m4":
        raise SystemExit("%s is not the M=4 export: %r" % (NOTE, txt[:60]))
    a = re.search(r"act=([0-9.eE+-]+)", txt)
    if not a:
        raise SystemExit("no act= in %s" % NOTE)
    return float(a.group(1))


def f32(v):
    """按 float32 打印，9 位有效数字 => 解析回来逐位相同。"""
    return "%.9g" % float(np.float32(v))


def emit_floats(fh, name, vals, per_line=PER_LINE_W, ctype="float"):
    vals = np.asarray(vals).reshape(-1)
    fh.write("static const %s %s[%d] = {\n" % (ctype, name, vals.size))
    line = []
    for v in vals:
        line.append(f32(v))
        if len(line) == per_line:
            fh.write("    " + ", ".join(line) + ",\n")
            line = []
    if line:
        fh.write("    " + ", ".join(line) + ",\n")
    fh.write("};\n\n")


def emit_ints(fh, name, vals, ctype="int16_t", per_line=PER_LINE_I):
    vals = np.asarray(vals).reshape(-1)
    fh.write("static const %s %s[%d] = {\n" % (ctype, name, vals.size))
    line = []
    for v in vals:
        line.append("%d" % int(v))
        if len(line) == per_line:
            fh.write("    " + ", ".join(line) + ",\n")
            line = []
    if line:
        fh.write("    " + ", ".join(line) + ",\n")
    fh.write("};\n\n")


def main():
    h = PSHead(W_NPZ)
    G, d, H, ncls = h.n_groups, h.d, h.hidden, 3
    if (G, d, H) != (16, 16, 64):
        raise SystemExit("unexpected geometry G=%d d=%d hidden=%d" % (G, d, H))
    if h.agg_mode != "attn":
        raise SystemExit("agg mode is %r, this generator only handles 'attn'" % h.agg_mode)
    if list(h.mods) != MODS:
        raise SystemExit("mods are %r, expected %r" % (h.mods, MODS))

    act = read_act()
    vec = np.load(VEC, allow_pickle=False)
    Zp_i = {m: vec["zp" + m].astype(np.int64).reshape(1, G, d) for m in MODS}

    # ---- 参考值：与板上 Python 路径同一份代码、同一档（吃 INT16）
    Zp_f = h.dequant(Zp_i, np.float32(act))
    logits, z = h.forward(Zp_f)
    logits = np.asarray(logits, dtype=np.float64).reshape(-1)
    lg32 = np.asarray(h.forward(Zp_f)[0], dtype=np.float32).reshape(-1)
    e = np.exp(logits - logits.max())
    prob = e / e.sum()
    cls = int(prob.argmax())

    w = h.w
    os.makedirs(SRC, exist_ok=True)

    with open(OUT_W, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("/* head_m4_w.h -- GENERATED by gen_head.py, do not edit.\n"
                 " *\n"
                 " * source : _board/w_attn4_p_emotion_v_f0.npz\n"
                 " *          (same file work2/export.py m4 used for attn4_e4.bit)\n"
                 " * layout : mods e,o,a,s  G=16  d=16  hidden=64  classes=3\n"
                 " *\n"
                 " * All weights are float32, printed with 9 significant digits, so\n"
                 " * the parsed value is the same float32 bit pattern as in the npz.\n"
                 " */\n")
        fh.write("#ifndef HEAD_M4_W_H\n#define HEAD_M4_W_H\n\n")
        # (M, d, d)  每模态一份 Wa（在 G 个组上共用），按 [m][out][in] 排
        wa = np.stack([w["agg.Wa.%s.weight" % m] for m in MODS])
        fh.write("/* agg.Wa: (M,d,d), shared over the G groups\n"
                 " *         -> t[g] = tanh(x[g] @ Wa^T + ba) */\n")
        emit_floats(fh, "HEAD_WA", wa)
        emit_floats(fh, "HEAD_BA", np.stack([w["agg.Wa.%s.bias" % m] for m in MODS]))
        fh.write("/* agg.wa: (M,d) -> s_g = t_g . wa + bwa, softmax over g */\n")
        emit_floats(fh, "HEAD_WWA",
                    np.stack([w["agg.wa.%s.weight" % m].reshape(-1) for m in MODS]))
        emit_floats(fh, "HEAD_BWA",
                    np.stack([w["agg.wa.%s.bias" % m].reshape(-1) for m in MODS]))
        fh.write("/* head.0: (hidden, M*d) -> h1 = relu(zc @ W0^T + b0) */\n")
        emit_floats(fh, "HEAD_W0", w["head.0.weight"])
        emit_floats(fh, "HEAD_B0", w["head.0.bias"])
        fh.write("/* head.3: (ncls, hidden) -> logits = h1 @ W3^T + b3 */\n")
        emit_floats(fh, "HEAD_W3", w["head.3.weight"])
        emit_floats(fh, "HEAD_B3", w["head.3.bias"])
        a1 = np.asarray(w["head.0.weight"]).reshape(-1).argmax()
        fh.write("#endif /* HEAD_M4_W_H */\n")

    with open(OUT_G, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("/* head_m4_gold.h -- GENERATED by gen_head.py, do not edit.\n"
                 " *\n"
                 " * act    : _pl/work2/out_m4_snapshot/exp_note.txt (the export that\n"
                 " *          produced the live attn4_e4.bit)\n"
                 " * input  : _pl/deploy/attn_vectors4.npz zp{e,o,a,s} (INT16, board-\n"
                 " *          verified bit-exact against the PL)\n"
                 " * golden : _board/ps_head.py on those INT16 values x act\n"
                 " */\n")
        fh.write("#ifndef HEAD_M4_GOLD_H\n#define HEAD_M4_GOLD_H\n\n")
        fh.write("#include <stdint.h>\n\n")
        fh.write("#define HEAD_ACT          %s\n" % f32(act))
        fh.write("#define HEAD_GOLD_CLASS   %d\n" % cls)
        fh.write("#define HEAD_TOL_LOGIT    %s   /* abs, vs float32 numpy path */\n"
                 % "1e-3f")
        fh.write("\n")
        emit_floats(fh, "HEAD_GOLD_LOGITS", lg32.astype(np.float64), per_line=3)
        emit_floats(fh, "HEAD_GOLD_PROB", prob, per_line=3)
        fh.write("/* z after module 3: (M, d) in mods order e,o,a,s */\n")
        emit_floats(fh, "HEAD_GOLD_Z",
                    np.stack([np.asarray(z[m]).reshape(-1) for m in MODS]))
        fh.write("#endif /* HEAD_M4_GOLD_H */\n")

    # ---- 供 PC 端 C 自检用的输入向量（板上不需要，板子自己从 scratch 读）
    emit = os.path.join(SRC, "zp_m4_vec.h")
    with open(emit, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("/* zp_m4_vec.h -- GENERATED by gen_head.py.\n"
                 " * Zp as the PL leaves it in scratch (INT16, 4 x 16 x 16).\n"
                 " * Only the PC-side self test reads this; the board reads scratch. */\n")
        fh.write("#ifndef ZP_M4_VEC_H\n#define ZP_M4_VEC_H\n\n#include <stdint.h>\n\n")
        emit_ints(fh, "ZP_VEC", np.stack([Zp_i[m].reshape(-1) for m in MODS]))
        fh.write("#endif /* ZP_M4_VEC_H */\n")

    np_s = lambda v: " ".join("%+.4f" % x for x in v)
    print("act = %.9g   (from %s)" % (act, os.path.relpath(NOTE, ROOT)))
    print("logits  %s   -> class %d" % (np_s(logits), cls))
    print("probs   %s" % np_s(prob))
    for m in MODS:
        zz = np.asarray(z[m]).reshape(-1)
        print("  z[%s] %s" % (m, " ".join("%+.4f" % v for v in zz[:4]) + " ..."))
    print("wrote %s (%d B)" % (OUT_W, os.path.getsize(OUT_W)))
    print("wrote %s (%d B)" % (OUT_G, os.path.getsize(OUT_G)))
    print("wrote %s (%d B)" % (emit, os.path.getsize(emit)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
